// Clearway — PDF exports: the two-page Flight Safety Brief and the draft Compliance Data Pack.
// The compliance pack is a set of pre-filled DRAFT texts and data tables for the team to copy
// into the official channels (aviation NOTAM request, maritime navigational warning, launch
// conjunction assessment request, licence application). It is not an official form.

import { PdfDoc, A4, wrap, textWidth } from './pdf.js';
import { dm } from './hazards.js';

const C = { ink: '#132033', muted: '#56647a', line: '#c9d1dc', band: '#0d131e', accent: '#0b7f97', soft: '#eef2f6', GO: '#12885a', CLEAR: '#12885a', CAUTION: '#a86c00', 'NO-GO': '#c8303a', 'NO DATA': '#6b7486' };
const M = 42; // page margin
const fmtUtc = (t) => new Date(t).toISOString().slice(0, 19).replace('T', ' ') + ' UTC';
const f = (v, d = 1) => (v == null || !Number.isFinite(v) ? '-' : v.toFixed(d));
const DEG = 180 / Math.PI;

// The Clearway logo (a baseline JPEG on the header colour), set once by the app: {data, w, h}.
let LOGO = null;
export function setPdfLogo(img) { LOGO = img && img.data ? img : null; }

function header(p, title, sub, pageNo, pages) {
  p.rect(0, 0, A4.w, 64, { fill: C.band });
  const x0 = LOGO ? M + 50 : M;
  if (LOGO) p.image(LOGO, M, 8, 48, 48);
  p.text(x0, 28, 'CLEARWAY', { font: 'F2', size: 15, color: '#ffffff' });
  p.text(x0 + 92, 28, title, { font: 'F1', size: 12, color: '#9fb3c8' });
  let line = sub;
  while (line.length > 8 && textWidth(line, 9) > A4.w - 2 * M - 210 - (x0 - M)) line = line.slice(0, -2);
  p.text(x0, 48, line === sub ? sub : line.trimEnd() + '...', { size: 9, color: '#c7d3e0' });
  p.text(A4.w - M, 28, `Page ${pageNo} of ${pages}`, { size: 9, color: '#c7d3e0', align: 'right' });
  p.text(A4.w - M, 48, 'PLANNING AID - NOT AN OFFICIAL CLEARANCE', { font: 'F2', size: 8, color: '#ffb35c', align: 'right' });
}

function footer(p, generatedAt, note) {
  p.line(M, A4.h - 36, A4.w - M, A4.h - 36, { color: C.line });
  p.text(M, A4.h - 24, `${fmtUtc(generatedAt)} · ${note || 'Generated by Clearway. Does not replace launch collision avoidance screening by the 18th/19th SDS or a national equivalent, range safety approval or licensing.'}`, { size: 6.5, color: C.muted });
}

function sectionTitle(p, y, t) {
  p.text(M, y, t.toUpperCase(), { font: 'F2', size: 9, color: C.accent });
  p.line(M, y + 4, A4.w - M, y + 4, { color: C.accent, width: 0.8 });
  return y + 16;
}

function kvTable(p, x, y, w, rows, { k = 0.38, size = 8.5 } = {}) {
  const lh = size * 1.3;
  for (const [key, val] of rows) {
    const lines = wrap(String(val ?? '-'), w * (1 - k) - 6, size);
    p.text(x, y, key, { size, color: C.muted });
    lines.forEach((ln, i) => p.text(x + w * k, y + i * lh, ln, { size, color: C.ink }));
    const bottom = y + (Math.max(1, lines.length) - 1) * lh + 4;
    p.line(x, bottom, x + w, bottom, { color: '#e3e8ef', width: 0.4 });
    y = bottom + size + 4;
  }
  return y;
}

function table(p, x, y, cols, rows, { size = 7.5, rowH = 12, maxRows = 99 } = {}) {
  const W = cols.reduce((s, c) => s + c.w, 0);
  p.rect(x, y - 9, W, rowH, { fill: C.soft });
  let cx = x;
  for (const c of cols) { p.text(c.align === 'right' ? cx + c.w - 4 : cx + 4, y, c.label, { font: 'F2', size: size - 0.5, color: C.muted, align: c.align || 'left' }); cx += c.w; }
  y += rowH;
  for (const r of rows.slice(0, maxRows)) {
    cx = x;
    cols.forEach((c, i) => {
      const cell = r[i];
      const val = typeof cell === 'object' && cell ? cell.v : cell;
      const color = typeof cell === 'object' && cell ? cell.color : C.ink;
      let s = String(val ?? '');
      while (s.length > 3 && (s.length * size * 0.5) > c.w - 6) s = s.slice(0, -2);
      p.text(c.align === 'right' ? cx + c.w - 4 : cx + 4, y, s, { size, color, align: c.align || 'left', font: c.mono ? 'F3' : 'F1' });
      cx += c.w;
    });
    p.line(x, y + 3.5, x + W, y + 3.5, { color: '#e3e8ef', width: 0.4 });
    y += rowH;
  }
  return y;
}

function statusPill(p, x, y, label, status) {
  const col = C[status] || C['NO DATA'];
  const txt = `${label} ${status}`;
  const w = textWidth(txt, 8, 'F2') + 12;
  p.rect(x, y - 10, w, 15, { stroke: col, width: 1 });
  p.text(x + 6, y, txt, { font: 'F2', size: 8, color: col });
  return x + w + 6;
}

/** Map of the hazard area: equirectangular, aspect-correct, clipped. */
function hazardMap(p, x, y, w, h, hz, site, land) {
  const pts = [...hz.track.map(([lo, la]) => [lo, la]), ...(hz.corridor || []), ...(hz.impact || []), [site.lon, site.lat]];
  let lomin = Math.min(...pts.map((q) => q[0])), lomax = Math.max(...pts.map((q) => q[0]));
  let lamin = Math.min(...pts.map((q) => q[1])), lamax = Math.max(...pts.map((q) => q[1]));
  const padLo = (lomax - lomin) * 0.12 + 0.5, padLa = (lamax - lamin) * 0.12 + 0.5;
  lomin -= padLo; lomax += padLo; lamin -= padLa; lamax += padLa;
  const k = Math.cos(((lamin + lamax) / 2) * Math.PI / 180);
  let sx = w / ((lomax - lomin) * k), sy = h / (lamax - lamin);
  const s = Math.min(sx, sy);
  const cxLo = (lomin + lomax) / 2, cyLa = (lamin + lamax) / 2;
  const X = (lo) => x + w / 2 + (lo - cxLo) * k * s, Y = (la) => y + h / 2 - (la - cyLa) * s;
  const vLoMin = cxLo - w / 2 / (k * s), vLoMax = cxLo + w / 2 / (k * s), vLaMin = cyLa - h / 2 / s, vLaMax = cyLa + h / 2 / s;
  p.rect(x, y, w, h, { fill: '#dce8f3', stroke: C.line });
  p.clip(x, y, w, h, (pg) => {
    for (const ring of land || []) {
      if (!ring.some(([lo, la]) => lo >= vLoMin - 5 && lo <= vLoMax + 5 && la >= vLaMin - 5 && la <= vLaMax + 5)) continue;
      pg.poly(ring.map(([lo, la]) => [X(lo), Y(la)]), { fill: '#f7f4ec', stroke: '#9aa9ba', width: 0.4, close: true });
    }
    const step = niceStep(Math.max(vLoMax - vLoMin, vLaMax - vLaMin) / 5);
    for (let lo = Math.ceil(vLoMin / step) * step; lo <= vLoMax; lo += step) pg.line(X(lo), y, X(lo), y + h, { color: '#b9c7d6', width: 0.3, dash: [2, 2] });
    for (let la = Math.ceil(vLaMin / step) * step; la <= vLaMax; la += step) pg.line(x, Y(la), x + w, Y(la), { color: '#b9c7d6', width: 0.3, dash: [2, 2] });
    if (hz.corridor) pg.poly(hz.corridor.map(([lo, la]) => [X(lo), Y(la)]), { fill: '#ff8a3d', stroke: '#d9620f', width: 0.8, close: true, alpha: 0.3 });
    if (hz.impact) pg.poly(hz.impact.map(([lo, la]) => [X(lo), Y(la)]), { fill: '#c8303a', stroke: '#c8303a', width: 0.8, close: true, alpha: 0.35 });
    pg.poly(hz.track.map(([lo, la]) => [X(lo), Y(la)]), { stroke: C.ink, width: 1, dash: [3, 2] });
    const sxp = X(site.lon), syp = Y(site.lat);
    pg.poly([[sxp, syp - 6], [sxp + 5, syp + 4], [sxp - 5, syp + 4]], { fill: C.accent, stroke: '#ffffff', width: 0.8, close: true });
    for (let lo = Math.ceil(vLoMin / step) * step; lo <= vLoMax; lo += step) pg.text(X(lo) + 2, y + h - 4, `${Math.abs(lo).toFixed(step < 1 ? 1 : 0)}°${lo < 0 ? 'W' : 'E'}`, { size: 6, color: C.muted });
    for (let la = Math.ceil(vLaMin / step) * step; la <= vLaMax; la += step) pg.text(x + 3, Y(la) - 2, `${Math.abs(la).toFixed(step < 1 ? 1 : 0)}°${la < 0 ? 'S' : 'N'}`, { size: 6, color: C.muted });
  });
  // legend
  const ly = y + h + 12;
  p.rect(x, ly - 7, 10, 7, { fill: '#ffb685' }); p.text(x + 14, ly, `Hazard corridor (±${hz.opts.corridorHalfWidthKm} km)`, { size: 7, color: C.muted });
  p.rect(x + 150, ly - 7, 10, 7, { fill: '#e49aa0' }); p.text(x + 164, ly, `Stage 1 impact area (${hz.opts.impactAlongKm * 2}×${hz.opts.impactCrossKm * 2} km)`, { size: 7, color: C.muted });
  p.line(x + 320, ly - 3, x + 334, ly - 3, { dash: [3, 2], width: 1 }); p.text(x + 338, ly, 'Ascent ground track', { size: 7, color: C.muted });
  return ly + 8;
}

function niceStep(raw) {
  const p10 = Math.pow(10, Math.floor(Math.log10(raw)));
  const n = raw / p10;
  return (n < 1.5 ? 1 : n < 3.5 ? 2 : n < 7.5 ? 5 : 10) * p10;
}

export function buildBriefing(ctx) {
  const { mission: m, plan, rec, rows, hazards: hz, stats, catalogInfo, spaceWeather: sw, generatedAt, land, optimisation, orbitOps } = ctx;
  const doc = new PdfDoc({ title: `${m.name} - Flight Safety Brief`, author: m.operator || 'Clearway' });
  const sub = `${m.name} · ${m.vehicle} · ${m.payload}`;

  // ---------------- page 1
  const p = doc.addPage();
  header(p, 'Flight Safety Brief', sub, 1, 2);
  let y = 92;
  const st = rec.overall;
  p.rect(M, y - 14, A4.w - 2 * M, 66, { fill: '#f6f8fa', stroke: C.line });
  p.rect(M, y - 14, 5, 66, { fill: C[st] });
  p.text(M + 16, y, 'RECOMMENDED T-0', { font: 'F2', size: 8, color: C.muted });
  p.text(M + 16, y + 22, fmtUtc(rec.t0), { font: 'F2', size: 20, color: C.ink });
  let px = M + 16;
  px = statusPill(p, px, y + 42, 'OVERALL', st);
  px = statusPill(p, px, y + 42, 'COLLISION', rec.col.status === 'CLEAR' ? 'GO' : rec.col.status);
  statusPill(p, px, y + 42, 'WEATHER', rec.wx.status);
  p.text(A4.w - M - 12, y, `${plan.windows.length} window(s) · ${rows.length} launch times screened`, { size: 8, color: C.muted, align: 'right' });
  p.text(A4.w - M - 12, y + 14, `${rows.filter((r) => r.overall === 'GO').length} go · ${rows.filter((r) => r.overall === 'CAUTION').length} caution · ${rows.filter((r) => r.overall === 'NO-GO').length} no-go`, { size: 8, color: C.muted, align: 'right' });
  if (optimisation?.improved) p.text(A4.w - M - 12, y + 28, `Hold optimiser: ${optimisation.best.hold >= 0 ? '+' : ''}${optimisation.best.hold} s applied`, { size: 8, color: C.accent, align: 'right' });
  y += 72;

  const colW = (A4.w - 2 * M - 20) / 2;
  let yl = sectionTitle(p, y, 'Mission');
  yl = kvTable(p, M, yl, colW, [
    ['Operator', m.operator], ['Country of origin', m.country], ['Licence / authorisation', m.licence || 'Not entered'],
    ['Launch vehicle', m.vehicle], ['Payload', `${m.payload}${m.massKg ? ` (${m.massKg} kg)` : ''}`],
    ['Launch site', `${m.site.name} (${m.site.lat.toFixed(4)}°, ${m.site.lon.toFixed(4)}°)`],
    ['Target orbit', `${m.orbit.hKm} km circular, ${f(plan.perf.incDeg, 2)}°`], ['Orbital plane', plan.planeLabel],
    ['Objective', m.objective || '-'],
  ]);
  const xr = M + colW + 20;
  p.text(xr, y, 'TRAJECTORY & PERFORMANCE', { font: 'F2', size: 9, color: C.accent });
  let yr = y + 16;
  yr = kvTable(p, xr, yr, colW, [
    ['Flight azimuth', `${f(rec.azR * DEG, 2)}° (inertial ${f(rec.azI * DEG, 2)}°)`], ['Pass', rec.pass === 'asc' ? 'Northbound' : 'Southbound'],
    ['Orbital velocity', `${f(plan.perf.vOrb, 3)} km/s`], ['Period', `${f(plan.perf.period / 60, 1)} min`],
    ['Earth-rotation assist', `${f(rec.dvAssist * 1000, 0)} m/s`],
    ['Plane error at T-0', m.orbit.mode === 'sso' ? `node time ${rec.nodeShiftMin >= 0 ? '+' : ''}${f(rec.nodeShiftMin, 1)} min` : `${f(rec.planeErrDeg, 3)}° (${f(rec.dvPlane * 1000, 1)} m/s)`],
    ['Estimated Δv to orbit', `${f(rec.dvTotal, 2)} km/s incl. ${m.ascent.lossesKms} km/s losses`],
    ['Time to orbit insertion', `${m.ascent.tInsSec} s, ${m.ascent.downrangeKm} km downrange`],
  ]);
  y = Math.max(yl, yr) + 6;

  y = sectionTitle(p, y, 'Launch environment at T-0');
  const v = rec.wx.values || {};
  y = kvTable(p, M, y, A4.w - 2 * M, [
    ['Site weather', `${rec.wx.status}${rec.wx.reasons.length ? ' - ' + rec.wx.reasons.join('; ') : ' - all limits met'}`],
    ['Surface wind / gusts', `${f(v.wind)} / ${f(v.gust)} m/s   (limits ${m.weatherLimits.surfaceWindMs} / ${m.weatherLimits.gustMs})`],
    ['Upper-level wind', `${f(v.upper, 0)} m/s   (limit ${m.weatherLimits.upperWindMs})`],
    ['Rain · cloud · CAPE', `${f(v.precip)} mm/h · ${f(v.cloud, 0)}% · ${f(v.cape, 0)} J/kg`],
    ['Space weather (NOAA SWPC)', sw ? `Kp ${f(sw.kp, 1)} now (${sw.gNow}), max ${f(sw.kpMax, 1)} forecast 72 h (${sw.gMax}) · F10.7 ${f(sw.f107, 0)} sfu · uncertainty factor ×${f(m.screening.swFactor, 2)}` : 'Not loaded'],
  ], { k: 0.26 });

  y = sectionTitle(p, y + 2, 'Launch windows');
  const winRows = plan.windows.slice(0, 8).map((w) => {
    const wr = rows.filter((r) => r.windowId === w.id);
    const best = [...wr].sort((a, b) => a.score - b.score)[0];
    return [String(w.id + 1), w.pass === 'asc' ? 'North' : 'South', `${f(w.azR * DEG, 1)}°`, w.tPlanar ? fmtUtc(w.tPlanar) : fmtUtc(wr[0].t0), fmtUtc(best.t0), { v: best.overall, color: C[best.overall] }, String(best.col.events.length), best.wx.status];
  });
  y = table(p, M, y + 4, [
    { label: '#', w: 22 }, { label: 'Pass', w: 40 }, { label: 'Azimuth', w: 48, align: 'right' }, { label: 'Opens / in-plane', w: 118 },
    { label: 'Best T-0', w: 118 }, { label: 'Status', w: 56 }, { label: 'Conj.', w: 36, align: 'right' }, { label: 'Weather', w: 73 },
  ], winRows);
  footer(p, generatedAt);

  // ---------------- page 2
  const q = doc.addPage();
  header(q, 'Flight Safety Brief', sub, 2, 2);
  y = sectionTitle(q, 92, `Close approaches for recommended T-0 (${rec.col.events.length})`);
  if (rec.col.events.length) {
    y = table(q, M, y + 4, [
      { label: 'Object', w: 132 }, { label: 'NORAD', w: 42, align: 'right' }, { label: 'Phase', w: 44 }, { label: 'T+ (s)', w: 46, align: 'right' },
      { label: 'Miss (km)', w: 52, align: 'right' }, { label: 'Rel. v (km/s)', w: 62, align: 'right' }, { label: 'Pc', w: 56, align: 'right' }, { label: 'Severity', w: 77 },
    ], rec.col.events.map((e) => [e.name, String(e.norad), e.phase, f(e.tau, 0), f(e.miss, 2), f(e.relV, 2), e.pc ? e.pc.toExponential(1) : '0', { v: e.severity === 'red' ? 'NO-GO' : e.severity === 'amber' ? 'CAUTION' : 'INFO', color: e.severity === 'red' ? C['NO-GO'] : e.severity === 'amber' ? C.CAUTION : C.muted }]), { maxRows: 12 });
  } else {
    q.text(M, y + 6, `No tracked object within ${m.screening.reportKm} km during ascent and the first ${m.screening.orbits} orbit(s).`, { size: 9 });
    y += 16;
  }
  y += 8;
  y = sectionTitle(q, y, 'Launch hazard areas');
  const mapH = 250;
  y = hazardMap(q, M, y, A4.w - 2 * M, mapH, hz, m.site, land);
  y += 6;
  y = kvTable(q, M, y, A4.w - 2 * M, [
    ['Stage 1 impact centre', hz.impactCenter ? dm(hz.impactCenter[1], hz.impactCenter[0]) : 'Beyond modelled ascent'],
    ['Ground track to insertion', `${f(hz.trackLengthKm, 0)} km`],
    ...(orbitOps ? [['In-orbit advisory', `${orbitOps.events.filter((e) => e.severity !== 'info').length} caution/no-go approaches in the first ${orbitOps.days} days after insertion`]] : []),
  ], { k: 0.26 });
  y = sectionTitle(q, y + 2, 'Method & data lineage');
  q.para(M, y, `Catalog: ${catalogInfo}. Objects propagated with SGP4 from US Space Force GP element sets (via CelesTrak / Space-Track). Vehicle: simplified ascent to direct insertion, then a circular orbit with J2 drift. Screening at a ${m.screening.stepSec} s grid with SGP4 refinement (${stats ? stats.objectsConsidered.toLocaleString() : '-'} objects considered). Pc from a modelled RIC covariance (TLEs carry none) projected on the encounter plane; object uncertainty grows with element-set age, low altitude and space weather. Weather: Open-Meteo. Space weather: NOAA SWPC.`, A4.w - 2 * M, { size: 7.5, color: C.muted });
  footer(q, generatedAt);
  return doc.toBytes();
}

// ------------------------------------------------------------------ compliance pack
const ddmm = (lat, lon) => {
  const a = Math.abs(lat), b = Math.abs(lon);
  const la = `${String(Math.floor(a)).padStart(2, '0')}${String(Math.round((a % 1) * 60) % 60).padStart(2, '0')}${lat >= 0 ? 'N' : 'S'}`;
  const lo = `${String(Math.floor(b)).padStart(3, '0')}${String(Math.round((b % 1) * 60) % 60).padStart(2, '0')}${lon >= 0 ? 'E' : 'W'}`;
  return la + lo;
};
const notamTime = (t) => { const d = new Date(t); return `${String(d.getUTCFullYear()).slice(2)}${String(d.getUTCMonth() + 1).padStart(2, '0')}${String(d.getUTCDate()).padStart(2, '0')}${String(d.getUTCHours()).padStart(2, '0')}${String(d.getUTCMinutes()).padStart(2, '0')}`; };

/** Reduce a polygon to at most n vertices by even sampling (keeps the outline for notices). */
export function simplify(poly, n = 12) {
  if (!poly || poly.length <= n) return poly || [];
  const ring = poly[0][0] === poly.at(-1)[0] && poly[0][1] === poly.at(-1)[1] ? poly.slice(0, -1) : poly;
  const out = [];
  for (let i = 0; i < n; i++) out.push(ring[Math.floor((i * ring.length) / n)]);
  return out;
}

export function compliancePackText(ctx) {
  const { mission: m, rec, hazards: hz, plan } = ctx;
  const wins = plan.windows.map((w) => w.candidates).flat();
  const start = Math.min(...wins.map((c) => c.t0)) - 30 * 60000, end = Math.max(...wins.map((c) => c.t0)) + 60 * 60000;
  const corridor = simplify(hz.corridor, 10).map(([lo, la]) => ddmm(la, lo));
  const impact = simplify(hz.impact, 8).map(([lo, la]) => ddmm(la, lo));
  const notam = [
    'Q) [FIR]/QWMLW/IV/BO/W/000/999/[center+radius]',
    'A) [FIR ICAO]  B) ' + notamTime(start) + '  C) ' + notamTime(end),
    'D) [daily schedule if multi-day]',
    `E) ROCKET LAUNCH ${m.vehicle.toUpperCase()} WILL TAKE PLACE WI AREA BOUNDED BY: ${corridor.join(' ')} ${corridor[0] || ''}.`,
    `   STAGE 1 IMPACT AREA: ${impact.join(' ')} ${impact[0] || ''}.`,
    'F) SFC  G) UNL',
  ];
  const navwarn = [
    `[NAVAREA/COASTAL WARNING ID]`,
    `[REGION]. ROCKET LAUNCHING ${notamTime(start).slice(0, 6)} TO ${notamTime(end).slice(0, 6)} UTC,`,
    `${new Date(start).toISOString().slice(11, 16).replace(':', '')}Z TO ${new Date(end).toISOString().slice(11, 16).replace(':', '')}Z DAILY.`,
    `HAZARDOUS OPERATIONS (FALLING STAGES AND DEBRIS) IN AREA BOUNDED BY ${impact.join(', ')}.`,
    `ALTERNATE DATES: [ ]. CANCEL THIS MSG ${notamTime(end + 86400000).slice(0, 6)} [ ]Z.`,
  ];
  return { notam, navwarn, start, end, corridor, impact };
}

export function buildCompliancePack(ctx) {
  const { mission: m, rec, hazards: hz, plan, generatedAt } = ctx;
  const t = compliancePackText(ctx);
  const doc = new PdfDoc({ title: `${m.name} - Compliance Data Pack (draft)`, author: m.operator || 'Clearway' });
  const sub = `${m.name} · ${m.vehicle} · ${m.payload} · DRAFT for transfer to official forms`;
  const p = doc.addPage();
  header(p, 'Compliance Data Pack', sub, 1, 2);
  let y = 90;
  p.rect(M, y - 12, A4.w - 2 * M, 34, { fill: '#fff4e5', stroke: '#e0a24e' });
  y = p.para(M + 10, y + 2, 'DRAFT. These texts and tables are pre-filled from the mission data to save transcription time. They are not filings. Bracketed fields [ ] must be completed, and every value must be checked by the operator before it is entered in the official system of the competent authority.', A4.w - 2 * M - 20, { size: 8, color: '#7a4d00' }) + 14;

  y = sectionTitle(p, y, '1. Aviation: NOTAM request data (ICAO format, draft)');
  y = p.para(M, y, 'Submit through the air navigation service provider responsible for the flight information region(s) crossed. Q-code WMLW = missile, gun or rocket firing will take place. Confirm FIR, radius and schedule with the ANSP.', A4.w - 2 * M, { size: 8, color: C.muted }) + 4;
  const notamLines = t.notam.flatMap((line) => wrap(line, A4.w - 2 * M - 16, 7.5, 'F3'));
  p.rect(M, y - 9, A4.w - 2 * M, notamLines.length * 11 + 12, { fill: '#f6f8fa', stroke: C.line });
  for (const l of notamLines) { p.text(M + 8, y + 2, l, { font: 'F3', size: 7.5 }); y += 11; }
  y += 18;

  y = sectionTitle(p, y, '2. Maritime: navigational warning text (draft)');
  y = p.para(M, y, 'Send to the NAVAREA coordinator or national hydrographic office for the sea areas under the stage impact zones, normally well in advance of the window.', A4.w - 2 * M, { size: 8, color: C.muted }) + 4;
  const navwarnLines = t.navwarn.flatMap((line) => wrap(line, A4.w - 2 * M - 16, 7.5, 'F3'));
  p.rect(M, y - 9, A4.w - 2 * M, navwarnLines.length * 11 + 12, { fill: '#f6f8fa', stroke: C.line });
  for (const l of navwarnLines) { p.text(M + 8, y + 2, l, { font: 'F3', size: 7.5 }); y += 11; }
  y += 18;

  y = sectionTitle(p, y, '3. Hazard area coordinates');
  const corr = simplify(hz.corridor, 10);
  const half = Math.ceil(corr.length / 2);
  y = table(p, M, y + 4, [{ label: 'Corridor vertex', w: 90 }, { label: 'Lat / Lon (DM)', w: 160, mono: true }, { label: 'Vertex', w: 60 }, { label: 'Lat / Lon (DM)', w: 160, mono: true }],
    corr.slice(0, half).map(([lo, la], i) => [`C${i + 1}`, dm(la, lo), corr[i + half] ? `C${i + half + 1}` : '', corr[i + half] ? dm(corr[i + half][1], corr[i + half][0]) : '']));
  y += 4;
  if (hz.impactCenter) p.text(M, y, `Stage 1 impact ellipse centre ${dm(hz.impactCenter[1], hz.impactCenter[0])}, ${hz.opts.impactAlongKm * 2} × ${hz.opts.impactCrossKm * 2} km (approximate; replace with the flight safety analysis).`, { size: 8 });
  footer(p, generatedAt);

  const q = doc.addPage();
  header(q, 'Compliance Data Pack', sub, 2, 2);
  y = sectionTitle(q, 92, '4. Launch conjunction assessment request data');
  y = q.para(M, y, 'For the national space surveillance service (in the US, launch collision avoidance by the 18th/19th Space Defense Squadron, requested through the licensing process with the vehicle ephemeris). Clearway\'s screening below is the operator\'s own pre-assessment.', A4.w - 2 * M, { size: 8, color: C.muted }) + 4;
  y = kvTable(q, M, y, A4.w - 2 * M, [
    ['Launch site', `${m.site.name}, ${m.site.lat.toFixed(4)}°, ${m.site.lon.toFixed(4)}°`],
    ['Window (all opportunities)', `${fmtUtc(t.start + 30 * 60000)} to ${fmtUtc(t.end - 60 * 60000)}`],
    ['Recommended T-0', fmtUtc(rec.t0)],
    ['Target orbit', `${m.orbit.hKm} km circular, inclination ${f(plan.perf.incDeg, 3)}°`],
    ['Flight azimuth', `${f(rec.azR * DEG, 2)}°`],
    ['Objects screened / approaches', `${ctx.stats?.objectsConsidered?.toLocaleString() ?? '-'} / ${rec.col.events.length} within ${m.screening.reportKm} km`],
    ['Crewed-object stand-off used', `${m.screening.crewedStandoffKm} km`],
    ['Vehicle ephemeris file', '[ attach nominal trajectory, e.g. CCSDS OEM ]'],
  ], { k: 0.3 });
  y = sectionTitle(q, y + 4, '5. Licence application checklist (mission data)');
  y = kvTable(q, M, y, A4.w - 2 * M, [
    ['Operator / applicant', m.operator || '[ ]'], ['State of registry / origin', m.country || '[ ]'], ['Licence or authorisation ref.', m.licence || '[ ]'],
    ['Launch vehicle', m.vehicle], ['Payload and mass', `${m.payload}${m.massKg ? `, ${m.massKg} kg` : ''}`], ['Mission objective', m.objective || '[ ]'],
    ['Orbital lifetime / disposal plan', '[ e.g. deorbit within 5 years of mission end ]'], ['Radio frequencies / ITU filing', '[ national administration reference ]'],
    ['Third-party liability insurance', '[ ]'], ['Range safety approval', '[ ]'],
  ], { k: 0.3 });
  y = sectionTitle(q, y + 4, 'Sign-off');
  for (const role of ['Flight safety officer', 'Mission director', 'Licensing contact']) {
    q.text(M, y + 18, role, { size: 8, color: C.muted });
    q.line(M + 130, y + 20, M + 330, y + 20, { color: C.line });
    q.text(M + 340, y + 18, 'Date', { size: 8, color: C.muted });
    q.line(M + 370, y + 20, A4.w - M, y + 20, { color: C.line });
    y += 26;
  }
  footer(q, generatedAt);
  return doc.toBytes();
}

